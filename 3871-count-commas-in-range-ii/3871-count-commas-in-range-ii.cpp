class Solution {
public:
    long long countCommas(long long n) {
        long long c=0;
        
            if(n>=1000 && n<=999999)
        c=n-999;
        if(n>=1000000 &&n<=999999999 )
        c=999999-999+2*(n-999999);
         if(n>=1000000000 &&n<=999999999999 )
        c=999999-999+2*(999999999-999999)+3*(n-999999999);
         if(n>=1000000000000 &&n<=999999999999999 )
        c = (999999 - 999)+ 2 * (999999999 - 999999)+ 3 * (999999999999LL - 999999999)+ 4 * (n - 999999999999LL);

       if(n>=1000000000000000)
       c = (999999 - 999)
              + 2 * (999999999 - 999999)
              + 3 * (999999999999LL - 999999999)
              + 4 * (999999999999999LL - 999999999999LL)
              + 5 * (n - 999999999999999LL);

        
        return c;

        
    }
};